"""Governed Learning Loop: Feedback records and change proposals for Verifin."""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ChangeProposalStatus(str, Enum):
    PENDING_REVIEW = "PENDING_REVIEW"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"


class OfficerFeedbackRecord(BaseModel):
    """Immutable record of credit officer decisions and overrides."""
    case_id: str
    officer_id: str
    decision: str  # SANCTIONED, SENT_BACK, ESCALATED
    proposed_by_system_inr: float
    officer_sanctioned_inr: float
    override_reason: Optional[str] = None
    policy_pack_name: str
    policy_pack_version: str
    model_version: str = "mock-model-v1.0"
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class PolicyChangeProposal(BaseModel):
    """Proposal for policy pack threshold adjustment generated by the offline analysis job."""
    proposal_id: str
    policy_pack: str
    parameter: str
    current_value: float
    proposed_value: float
    justification_evidence: str
    supporting_case_count: int
    status: ChangeProposalStatus = Field(default=ChangeProposalStatus.PENDING_REVIEW)
    regression_gate_passed: bool = Field(default=False)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
